export function getLevelConfig(id: LevelId | string | null | undefined): LevelConfig {
  if (id && id in LEVELS) {
    return LEVELS[id as LevelId];
  }
  return LEVELS.op01;
}

export function getNextLevelId(current: LevelId): LevelId | null {
  const idx = LEVEL_ORDER.indexOf(current);
  if (idx >= 0 && idx + 1 < LEVEL_ORDER.length) {
    return LEVEL_ORDER[idx + 1];
  }
  return null;
}
